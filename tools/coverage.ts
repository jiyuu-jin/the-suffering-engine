// Port coverage report: which of the game's object classes the engine handles,
// weighted by how often each class is placed in the levels.
//
//   npx tsx tools/coverage.ts            all levels, writes docs/coverage.md
//   npx tsx tools/coverage.ts --chapter "1 PrisonDeathRow"
//
// "Referenced" means the class name appears as a string literal in engine code
// (src/game, src/app), or its class id appears as a hex literal there or in the
// decoders (src/formats, except the class table itself) — e.g. Portal, which the
// visibility code finds by id. A heuristic: it can't tell a full implementation
// from a stub, so treat it as an upper bound and keep docs/game-logic.md as the
// source of truth for fidelity.

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CLASS_ROWS, CATEGORY_NAMES } from '../src/formats/entity-classes';
import { parseEntities } from '../src/formats/entities';
import { readLevelHeader } from '../src/formats/level';
import { loadPackages } from '../src/app/loader';
import { dirname } from '../src/app/gamefs';
import { filesWithExt, hasData, nodeFS, readSrsc } from '../tests/helpers';

const args = process.argv.slice(2);
const chapter = args.includes('--chapter') ? args[args.indexOf('--chapter') + 1] : undefined;

function sources(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) sources(p, out);
    else if (/\.tsx?$/.test(name)) out.push(p);
  }
  return out;
}

async function main() {
  if (!hasData) throw new Error('No game data (set SUFFERING_DATA or extract to game/app)');
  console.warn = () => {};

  // Which class names does engine code mention?
  const code = [...sources('src/game'), ...sources('src/app')].map((f) => readFileSync(f, 'utf8')).join('\n');
  const idCode = [code, ...sources('src/formats').filter((f) => !f.endsWith('entity-classes.ts')).map((f) => readFileSync(f, 'utf8'))]
    .join('\n')
    .toLowerCase();
  const hexId = (id: number) => '0x' + (id >>> 0).toString(16).padStart(8, '0');
  const referenced = (name: string, id: number) => code.includes(`'${name}'`) || code.includes(`"${name}"`) || idCode.includes(hexId(id));

  // Placement counts per class, per level.
  const fs = nodeFS();
  const levels = filesWithExt('.lvl').filter((l) => !chapter || l.includes(`/${chapter}/`));
  const counts = new Map<string, Map<string, number>>();
  for (const path of levels) {
    const lvl = readSrsc(path);
    const packages = await loadPackages(fs, dirname(path), readLevelHeader(lvl).dependencies, () => {});
    for (const e of parseEntities(lvl, packages)) {
      let m = counts.get(e.className);
      if (!m) counts.set(e.className, (m = new Map()));
      const level = path.split('/').pop()!.replace(/\.lvl$/i, '');
      m.set(level, (m.get(level) ?? 0) + 1);
    }
  }

  type Row = { name: string; category: string; source: string; placed: number; levels: number; handled: boolean };
  const rows: Row[] = CLASS_ROWS.map((r) => {
    const per = counts.get(r[1]);
    const placed = per ? [...per.values()].reduce((a, b) => a + b, 0) : 0;
    return {
      name: r[1],
      category: CATEGORY_NAMES[r[2]] ?? String(r[2]),
      source: r[8],
      placed,
      levels: per?.size ?? 0,
      handled: referenced(r[1], r[0]),
    };
  });

  const used = rows.filter((r) => r.placed > 0);
  const handledUsed = used.filter((r) => r.handled);
  const totalPlaced = used.reduce((a, r) => a + r.placed, 0);
  const handledPlaced = handledUsed.reduce((a, r) => a + r.placed, 0);
  const pct = (a: number, b: number) => (b ? ((100 * a) / b).toFixed(1) : '0.0');

  const scope = chapter ? `chapter "${chapter}" (${levels.length} levels)` : `all ${levels.length} levels`;
  const lines = [
    '# Port coverage',
    '',
    `Generated by \`npx tsx tools/coverage.ts${chapter ? ` --chapter "${chapter}"` : ''}\` over ${scope}.`,
    '',
    '"Referenced" = the class name appears in engine code (src/game, src/app), or its class id as a hex literal there or in src/formats. It is an upper bound:',
    'a reference can be a stub. docs/game-logic.md records how faithfully each class is implemented.',
    '',
    `- Game classes in the binaries: ${rows.length} (${rows.filter((r) => r.source === 'rfl').length} game DLL, ${rows.filter((r) => r.source === 'exe').length} engine EXE)`,
    `- Classes actually placed in levels: ${used.length}`,
    `- Placed classes referenced by the engine: ${handledUsed.length}/${used.length} (${pct(handledUsed.length, used.length)}%)`,
    `- Placed objects whose class is referenced: ${handledPlaced}/${totalPlaced} (${pct(handledPlaced, totalPlaced)}%)`,
    '',
    '## Placed classes not referenced yet (by placement count)',
    '',
    '| Class | Category | Placed | Levels |',
    '|---|---|---|---|',
    ...used
      .filter((r) => !r.handled)
      .sort((a, b) => b.placed - a.placed)
      .map((r) => `| ${r.name} | ${r.category} | ${r.placed} | ${r.levels} |`),
    '',
    '## Placed classes referenced',
    '',
    '| Class | Category | Placed | Levels |',
    '|---|---|---|---|',
    ...handledUsed.sort((a, b) => b.placed - a.placed).map((r) => `| ${r.name} | ${r.category} | ${r.placed} | ${r.levels} |`),
    '',
  ];
  const out = chapter ? 'docs/coverage-chapter.md' : 'docs/coverage.md';
  writeFileSync(out, lines.join('\n'));
  console.log(lines.slice(6, 11).join('\n'));
  console.log(`\nwrote ${out}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
